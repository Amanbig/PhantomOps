// Package httpx holds tiny HTTP helpers shared by HTTP-based collectors.
package httpx

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"strings"
	"time"
)

// NewClient returns an HTTP client with a sane timeout.
func NewClient() *http.Client { return &http.Client{Timeout: 20 * time.Second} }

// GetJSON performs a GET against base+path with query parameters and decodes
// the JSON response into out.
func GetJSON(ctx context.Context, c *http.Client, base, path string, q url.Values, out any) error {
	u := strings.TrimRight(base, "/") + path
	if len(q) > 0 {
		u += "?" + q.Encode()
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, u, nil)
	if err != nil {
		return err
	}
	resp, err := c.Do(req)
	if err != nil {
		// Drop the full request URL (it can be huge, e.g. a LogQL query).
		var ue *url.Error
		if errors.As(err, &ue) {
			err = ue.Err
		}
		return fmt.Errorf("GET %s: %w", path, err)
	}
	defer resp.Body.Close()
	body, err := io.ReadAll(io.LimitReader(resp.Body, 32<<20))
	if err != nil {
		return err
	}
	if resp.StatusCode != http.StatusOK {
		msg := strings.TrimSpace(string(body))
		if len(msg) > 300 {
			msg = msg[:300] + "…"
		}
		return fmt.Errorf("GET %s: %s: %s", path, resp.Status, msg)
	}
	if err := json.Unmarshal(body, out); err != nil {
		return fmt.Errorf("decode %s: %w", path, err)
	}
	return nil
}
