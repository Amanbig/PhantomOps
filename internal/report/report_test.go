func TestRedact(t *testing.T) {
	cases := map[string]string{
		"password=hunter2 next":                                                "password=[redacted] next",
		`DB_PASSWORD: "p@ss w0rd"`:                                             "DB_PASSWORD: [redacted]",
		"api_key = abc123def456":                                               "api_key = [redacted]",
		"Authorization: Bearer eyJhbGciOi.abc.def":                             "Authorization: [redacted]",
		"retry with Bearer abcdefghijkl1234":                                   "retry with Bearer [redacted]",
		"postgres://admin:s3cret@db:5432/app":                                  "postgres://[redacted]@db:5432/app",
		"key AKIAIOSFODNN7EXAMPLE used":                                        "key [redacted key] used",
		"token ghp_abcdefghijklmnopqrstuvwxyz0123456789":                       "token [redacted token]",
		"https://hooks.slack.com/services/T0/B0/xyz fail":                      "[redacted webhook] fail",
		"https://discord.com/api/webhooks/1/abc fail":                          "[redacted webhook] fail",
		"-----BEGIN RSA PRIVATE KEY-----\nMIIE\n-----END RSA PRIVATE KEY-----": "[redacted private key]",
		"nothing secret here: 42 pods":                                         "nothing secret here: 42 pods",
	}
	for in, want := range cases {
		if got := Redact(in); got != want {
			t.Errorf("Redact(%q)\n got  %q\n want %q", in, got, want)
		}
	}
}

func TestSecretsInTimelineAndAuditAreRedacted(t *testing.T) {
	rec := record()
	rec.Latest.Timeline[0].Detail = "pulled registry://u:pw123@reg/api with token=abc999"
	rec.Latest.Investigation.RootCause = "bad secret: topsecret in env"
	audit := []remediate.Entry{{Time: t0, User: "u", Phase: "result", IncidentID: "inc1", Action: "rollback",
		Target: "x", Message: "failed: Authorization: Bearer abcdefghijkl1234"}}
	md := Markdown(rec, audit, Options{Now: t0})
	for _, leak := range []string{"pw123", "abc999", "topsecret", "abcdefghijkl1234"} {
		if strings.Contains(md, leak) {
			t.Errorf("%q leaked:\n%s", leak, md)
		}
	}
}

func TestLongTextIsBounded(t *testing.T) {
	rec := record()
	rec.Latest.Investigation.RootCause = strings.Repeat("x", 5000)
	rec.Latest.Timeline[0].Detail = strings.Repeat("y", 5000)
	if md := Markdown(rec, nil, Options{Now: t0}); len(md) > 6000 {
		t.Errorf("report too large: %d bytes", len(md))
	}
}
