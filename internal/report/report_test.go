package report

import (
	"strings"
	"testing"
	"time"

	"PhantomOps/internal/history"
	"PhantomOps/internal/model"
	"PhantomOps/internal/remediate"
)

var t0 = time.Date(2026, 3, 1, 10, 0, 0, 0, time.UTC)

func record() history.Record {
	ack := t0.Add(5 * time.Minute)
	return history.Record{
		ID: "inc1", Title: "api crash loop", Severity: model.SeverityCritical, Status: history.StatusResolved,
		FirstSeen: t0, LastSeen: t0.Add(42 * time.Minute), Scans: 9, Reopened: 1,
		AckBy: "amanpreet", AckAt: &ack,
		Latest: model.Incident{
			ID: "inc1", Environment: "prod",
			Timeline: []model.Event{
				{Time: t0, Source: model.SourceKubernetes, Kind: model.KindDeployment, Severity: model.SeverityInfo,
					Title: "Deployment api updated", Detail: "image api:v2", Subject: "default/api", Origin: "k3s"},
				{Time: t0.Add(time.Minute), Source: model.SourceLoki, Kind: model.KindLog, Severity: model.SeverityWarning,
					Title: "12 error log lines", Detail: "ERROR db password=hunter2 connection refused", Subject: "api"},
				{Time: t0.Add(2 * time.Minute), Source: model.SourceDocker, Kind: model.KindDegraded, Severity: model.SeverityCritical,
					Title: "api | restarting", Detail: "exit 1\nline two", Subject: "api"},
			},
			Investigation: model.Investigation{
				RootCause: "api broke after deploy v2", Confidence: 0.86, RecommendedAction: "Roll back default/api",
				Reasoning: []string{"deploy 1 min before the first error"}, Source: "rules",
			},
		},
	}
}

func TestMarkdownContainsTheStory(t *testing.T) {
	audit := []remediate.Entry{
		{Time: t0.Add(10 * time.Minute), User: "amanpreet", Phase: "approved", IncidentID: "inc1", Action: "rollback", Target: "default/api", OK: true},
		{Time: t0.Add(11 * time.Minute), User: "amanpreet", Phase: "result", IncidentID: "inc1", Action: "rollback", Target: "default/api", OK: true, Message: "rolled back"},
		{Time: t0, User: "someone", Phase: "result", IncidentID: "other", Action: "rollback", Target: "default/other", OK: true},
	}
	md := Markdown(record(), audit, Options{Now: t0.Add(time.Hour), Version: "v0.3.0"})
	for _, want := range []string{
		"# Incident report: api crash loop",
		"| Severity | critical |", "| Environment | prod |", "| Lasted | 42 min |", "| Came back | 1× |",
		"acknowledged by amanpreet at 2026-03-01 10:05 UTC",
		"api broke after deploy v2", "Confidence: 86%", "rule-based analysis",
		"- deploy 1 min before the first error", "Roll back default/api",
		"2026-03-01 10:00:00 | kubernetes", "Deployment api updated — image api:v2", "default/api (k3s)",
		"approved", "rolled back", "Generated by PhantomOps v0.3.0",
	} {
		if !strings.Contains(md, want) {
			t.Errorf("report is missing %q\n%s", want, md)
		}
	}
	if strings.Contains(md, "default/other") {
		t.Error("audit entries of other incidents must not appear")
	}
}

func TestLogExcerptsAreLeftOut(t *testing.T) {
	md := Markdown(record(), nil, Options{Now: t0})
	if strings.Contains(md, "connection refused") || strings.Contains(md, "hunter2") {
		t.Errorf("log detail leaked into the report:\n%s", md)
	}
	if !strings.Contains(md, "12 error log lines") || !strings.Contains(md, "Log excerpts are left out") {
		t.Errorf("log event title / omission note missing:\n%s", md)
	}
}

func TestTableCellsAreEscaped(t *testing.T) {
	md := Markdown(record(), nil, Options{Now: t0})
	if !strings.Contains(md, `api \| restarting — exit 1 line two`) {
		t.Errorf("pipe and newline not escaped:\n%s", md)
	}
}

func TestEmptySections(t *testing.T) {
	rec := record()
	rec.Latest.Timeline = nil
	rec.Latest.Investigation = model.Investigation{}
	rec.AckBy, rec.AckAt = "", nil
	md := Markdown(rec, nil, Options{Now: t0})
	for _, want := range []string{"_No events were recorded._", "_PhantomOps made no changes for this incident._", "Generated by PhantomOps dev"} {
		if !strings.Contains(md, want) {
			t.Errorf("missing %q\n%s", want, md)
		}
	}
	if strings.Contains(md, "Triage") || strings.Contains(md, "Confidence") {
		t.Errorf("unexpected rows for empty data:\n%s", md)
	}
}

